"""Version-1 script generation from a verified execution trace.

Design choice: the generated script is *data plus a tiny runtime call*, not a
bespoke hard-coded automation. That is what makes Phase 4 possible — rebinding a
new DUT means rewriting a PARAMS dict, and the diff between v1 and v2 is a diff
of the actual navigation/command changes the firmware forced, which a reviewer
can read in seconds.
"""
from __future__ import annotations

import json
from typing import Any

HEADER = '''#!/usr/bin/env python3
"""ITSAR scenario automation — clause {clause_no} / scenario {scenario_no}

  {scenario_title}

Auto-generated by the ITSAR Compliance Agent. Do not edit by hand: regenerate
or let the agent heal and re-version, so provenance stays intact.

  source device : {model} (firmware {firmware})
  source job    : {job_id}
  script version: v{version}
  generated     : {generated}

Run:  python3 {filename} --host <dut-ip>
"""
'''


def generate(
    *,
    device: dict,
    clause: dict,
    scenario: dict,
    trace: list[dict],
    pass_criteria: list[str],
    job_id: str,
    version: int,
    generated: str,
    parent_note: str = "",
) -> tuple[str, dict, dict]:
    steps = []
    for t in trace:
        if t.get("not_supported"):
            continue
        steps.append({
            "step_no": t["step_no"],
            "intent": t.get("intent", ""),
            "tool": t["tool"],
            "op": t["op"],
            "args": t.get("args") or {},
            "lock": t.get("lock") or {"kind": "net_idle"},
            "evidence": bool(t.get("evidence")),
        })

    params = {
        "mode": "mock",                    # "live" in production
        "host": device.get("host"),
        "mgmt_protocol": device.get("mgmt_protocol", "https"),
        "credential_ref": device.get("credential_ref"),
        "model": device.get("model"),
        "firmware": device.get("firmware"),
        "dut_profile": device.get("_profile_name", "old"),
        "scenario_no": scenario.get("scenario_no"),
        "clause_no": clause.get("clause_no"),
    }

    body = [
        HEADER.format(
            clause_no=clause.get("clause_no"), scenario_no=scenario.get("scenario_no"),
            scenario_title=scenario.get("title", ""), model=device.get("model"),
            firmware=device.get("firmware"), job_id=job_id, version=version,
            generated=generated,
            filename=f"scenario_{scenario.get('scenario_no')}_v{version}.py".replace(".", "_", 1),
        ).replace("__", "."),
        "",
        "# ---- rebind block for a new DUT in the same family -------------------",
        "PARAMS = " + repr(params),
        "",
        "# ---- verified execution path ----------------------------------------",
        "PASS_CRITERIA = " + repr(pass_criteria),
        "",
        "STEPS = " + repr(steps),
        "",
    ]
    if parent_note:
        body.append(f"# {parent_note}")
        body.append("")
    body += [
        "",
        "def main(argv=None):",
        "    from itsar.scripts.runtime import run_script",
        "    return run_script(__file__ if '__file__' in globals() else 'script', PARAMS, STEPS,",
        "                      PASS_CRITERIA, argv)",
        "",
        "",
        "if __name__ == '__main__':",
        "    raise SystemExit(main())",
        "",
    ]
    content = "\n".join(body)
    trace_meta: dict[str, Any] = {"steps": steps, "params": params}
    return content, params, trace_meta
